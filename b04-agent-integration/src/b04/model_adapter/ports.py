"""Ports to be implemented by B02/B03 integrations; no platform state is owned here."""
from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from typing import Any, Protocol

from .contracts import ControlContext, InvocationRef, JSON, ModelCallRef


@dataclass(frozen=True)
class ResolvedModel:
    config: JSON
    policy: JSON
    capabilities: JSON
    binding: JSON


@dataclass(frozen=True)
class TokenEstimate:
    tokens: int
    upper_bound: bool


class ConfigResolver(Protocol):
    def resolve(self, model_config_ref: str, context: ControlContext) -> ResolvedModel: ...
    def schema(self, schema_ref: str, context: ControlContext) -> Any: ...


class Authority(Protocol):
    def authorize(self, context: ControlContext, purpose: str, now: datetime) -> None: ...


class BudgetPort(Protocol):
    def consume_control(self, ticket_ref: str, invocation_ref: InvocationRef, now: datetime) -> None: ...
    def reserve(self, ticket_ref: str, transport_id: str, invocation_ref: InvocationRef, tokens: int, now: datetime) -> None: ...
    def settle(self, transport_id: str, *, delivery: str, usage: JSON) -> None: ...


class CredentialResolver(Protocol):
    def resolve(self, credential_ref: str, context: ControlContext) -> str: ...


class CallLedger(Protocol):
    def claim(self, request: JSON, fingerprint: str, attempt_fingerprint: str, metadata: JSON) -> tuple[bool, JSON]: ...
    def get(self, call_ref: ModelCallRef) -> JSON | None: ...
    def mark_sent(self, call_ref: ModelCallRef, transport_id: str) -> None: ...
    def finish(self, call_ref: ModelCallRef, result: JSON, state: str) -> None: ...
    def append(self, call_ref: ModelCallRef, kind: str, payload: JSON) -> None: ...
    def put_private(self, invocation_ref: InvocationRef, kind: str, value: Any) -> str: ...


class ProviderDriver(Protocol):
    execution_modes: frozenset[str]
    def describe(self) -> JSON: ...
    def validate_mapping(self, prepared: JSON) -> None: ...
    def estimate_input_tokens(self, prepared: JSON) -> TokenEstimate: ...
    async def send_once(self, prepared: JSON, credential: str | None, timeout_seconds: float) -> Any: ...
    def normalize(self, raw: Any) -> JSON: ...
    async def cancel(self, call_ref: ModelCallRef, provider_request_id: str | None) -> JSON: ...

