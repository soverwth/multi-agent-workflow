"""B02/B03/executor integration ports, intentionally independent of provider SDKs."""
from __future__ import annotations
from typing import Any, Protocol

from b04.model_adapter.contracts import CallControl, ControlContext, JSON
from .contracts import RunnerControls


class ControlProvider(Protocol):
    def acquire(self, invocation_ref: JSON) -> RunnerControls: ...


class FrozenCatalog(Protocol):
    def load(self, envelope: JSON, context: ControlContext) -> JSON: ...
    def describe(self, catalog_ref: str) -> JSON: ...


class ModelPort(Protocol):
    async def describe_model(self, model_config_ref: str, call_context: CallControl) -> JSON: ...
    async def validate_request(self, request: JSON, call_context: CallControl) -> JSON: ...
    async def generate(self, request: JSON, call_control: CallControl) -> JSON: ...
    async def get_call(self, model_call_ref: JSON, call_context: CallControl) -> JSON: ...
    async def cancel_call(self, model_call_ref: JSON, reason: str, call_context: CallControl) -> JSON: ...
    async def read_result(self, model_call_ref: JSON, result_ref: str, call_context: CallControl) -> JSON: ...


class ToolExecutorPort(Protocol):
    async def execute_tool(self, request: JSON, tool_control: CallControl) -> JSON: ...
    async def get_operation(self, operation_ref: JSON, access_context: CallControl) -> JSON: ...
    async def stop_operation(self, operation_ref: JSON, reason: str, tool_control: CallControl) -> JSON: ...
    async def read_result(self, operation_ref: JSON, result_ref: str, access_context: CallControl) -> JSON: ...


class EventSink(Protocol):
    async def submit_event(self, event: JSON) -> JSON: ...
    async def reconcile_terminal(self, request: JSON, report_context: ControlContext) -> JSON: ...


class TransportBudget(Protocol):
    def consume_transport(self, ticket_ref: str, invocation_ref: JSON) -> None: ...


class SourcePort(Protocol):
    def prepare(self, envelope: JSON, context: ControlContext) -> JSON: ...
    def capture(self, envelope: JSON, slots: list[JSON], context: ControlContext) -> tuple[JSON, dict[str, bytes]]: ...


class RunnerStore(Protocol):
    def admit(self, envelope: JSON, fingerprint: str, context: ControlContext) -> tuple[bool, JSON]: ...
    def get(self, ref: JSON, context: ControlContext) -> JSON: ...
    def read_execution_record(self, record_ref: str, context: ControlContext) -> JSON: ...
    def claim_execution(self, ref: JSON, owner: str, context: ControlContext, *, recover=False) -> JSON: ...
    def checkpoint(self, ref: JSON, owner: str | None, phase: str, checkpoint: JSON, context: ControlContext) -> None: ...
    def read_input(self, artifact_ref: str, project_id: str, context: ControlContext) -> JSON: ...
    def put_object(self, ref: JSON, name: str, kind: str, body: bytes, context: ControlContext, *, namespace: str | None = None, media_type="application/json", schema_ref=None) -> JSON: ...
    def read_object(self, artifact_ref: str, context: ControlContext) -> JSON: ...
    def reserve_action(self, ref: JSON, owner: str, name: str, kind: str, request: JSON, context: ControlContext) -> JSON: ...
    def action(self, ref: JSON, name: str, context: ControlContext) -> JSON | None: ...
    def actions(self, ref: JSON, context: ControlContext) -> list[JSON]: ...
    def set_action(self, ref: JSON, owner: str, name: str, state: str, result: JSON | None, context: ControlContext) -> None: ...
    def stage_draft_content(self, ref: JSON, operation_ref: JSON, origin_fingerprint: str, body: bytes, media_type: str, context: ControlContext) -> JSON: ...
    def commit_terminal(self, draft: JSON, context: ControlContext, *, owner: str | None = None) -> JSON: ...
    def get_terminal_submission(self, submission_id: str, context: ControlContext) -> JSON | None: ...
    def emit(self, ref: JSON, event_type: str, payload: JSON, context: ControlContext) -> JSON: ...
    def events(self, ref: JSON, context: ControlContext) -> list[JSON]: ...
    def delivery(self, event_id: str, status: str, receipt: JSON | None, context: ControlContext, *, reconciliation=None) -> None: ...
    def request_stop(self, ref: JSON, reason: str, context: ControlContext) -> None: ...
    def record_stop(self, ref: JSON, status: str, evidence: list, context: ControlContext) -> None: ...
    def mark_recovery(self, ref: JSON, owner: str | None, code: str, context: ControlContext) -> None: ...
    def note(self, ref: JSON, code: str, payload: JSON, context: ControlContext) -> str: ...

